//! Bundled client HUD mod: installs the jar and writes its properties config.
use crate::error::Result;
use crate::paths::GamePaths;
use crate::settings::{HudModule, HudSettings, Settings};
use std::path::{Path, PathBuf};

const HUD_JAR: &[u8] = include_bytes!("../resources/diamond-hud.jar");
pub const HUD_JAR_NAME: &str = "diamond-hud.jar";
pub const HUD_CONFIG_NAME: &str = "diamond-hud.properties";

/// Written by the launcher before each launch.
const LAUNCHER_MARKER: &str = "# Generated by Diamond Launcher (Settings > HUD).";
/// Written by the mod whenever the player changes something in-game.
const INGAME_MARKER: &str = "Modified in-game by Diamond HUD";

/// The overlay needs Fabric; `mods::enabled` adds Fabric API when this is true.
pub fn active(settings: &Settings, version: &str) -> bool {
    settings.hud.active() && supports(version)
}

/// The mod is compiled against the official-named 26.x client and uses the 26.x HUD API.
pub fn supports(version: &str) -> bool {
    let mut parts = version.split('.');
    let major: u32 = parts.next().and_then(|p| p.parse().ok()).unwrap_or(0);
    let minor: u32 = parts.next().and_then(|p| p.parse().ok()).unwrap_or(0);
    major > 26 || (major == 26 && minor >= 2)
}

/// Writes the embedded mod next to the game files so the JVM can load it.
pub fn install(paths: &GamePaths) -> Result<PathBuf> {
    let path = paths.root.join(HUD_JAR_NAME);
    let current = std::fs::read(&path).ok();
    if current.as_deref() != Some(HUD_JAR) {
        std::fs::create_dir_all(&paths.root)?;
        std::fs::write(&path, HUD_JAR)?;
    }
    Ok(path)
}

/// Writes `diamond-hud.properties`, the config the mod reads once per second.
/// If the properties file has the INGAME_MARKER (modified in-game), it imports
/// those changes first to avoid overwriting player changes made in-game.
pub fn write_config(paths: &GamePaths, hud: &HudSettings) -> Result<PathBuf> {
    let file = config_path(&paths.root);
    if let Some(dir) = file.parent() {
        std::fs::create_dir_all(dir)?;
    }
    
    // If the properties file has the INGAME_MARKER, import in-game changes first
    if file.exists() {
        if let Ok(text) = std::fs::read_to_string(&file) {
            if text.contains(INGAME_MARKER) {
                // Parse in-game config and merge: use in-game module states, launcher's other settings
                if let Some(ingame_hud) = parse_ingame(&text) {
                    let mut merged = hud.clone();
                    // Preserve in-game module enabled states and positions
                    merged.fps.enabled = ingame_hud.fps.enabled;
                    merged.fps.x = ingame_hud.fps.x;
                    merged.fps.y = ingame_hud.fps.y;
                    merged.cps.enabled = ingame_hud.cps.enabled;
                    merged.cps.x = ingame_hud.cps.x;
                    merged.cps.y = ingame_hud.cps.y;
                    merged.keystrokes.enabled = ingame_hud.keystrokes.enabled;
                    merged.keystrokes.x = ingame_hud.keystrokes.x;
                    merged.keystrokes.y = ingame_hud.keystrokes.y;
                    merged.coords.enabled = ingame_hud.coords.enabled;
                    merged.coords.x = ingame_hud.coords.x;
                    merged.coords.y = ingame_hud.coords.y;
                    merged.day.enabled = ingame_hud.day.enabled;
                    merged.day.x = ingame_hud.day.x;
                    merged.day.y = ingame_hud.day.y;
                    merged.ip.enabled = ingame_hud.ip.enabled;
                    merged.ip.x = ingame_hud.ip.x;
                    merged.ip.y = ingame_hud.ip.y;
                    merged.armor.enabled = ingame_hud.armor.enabled;
                    merged.armor.x = ingame_hud.armor.x;
                    merged.armor.y = ingame_hud.armor.y;
                    // Write merged config
                    let tmp = file.with_extension("properties.tmp");
                    std::fs::write(&tmp, properties(&merged))?;
                    std::fs::rename(&tmp, &file)?;
                    return Ok(file);
                }
            }
        }
    }
    
    let tmp = file.with_extension("properties.tmp");
    std::fs::write(&tmp, properties(hud))?;
    std::fs::rename(&tmp, &file)?;
    Ok(file)
}

fn properties(hud: &HudSettings) -> String {
    let mut out = String::new();
    out.push_str(LAUNCHER_MARKER);
    out.push('\n');
    out.push_str(&format!("enabled={}\n", hud.enabled));
    out.push_str(&format!("scale={:.3}\n", hud.scale));
    out.push_str(&format!("background={:.3}\n", hud.background_opacity));
    out.push_str(&format!("accent={}\n", hud.accent));
    out.push_str(&format!("text={}\n", hud.text_color));
    out.push_str(&format!("keybind={}\n", hud.keybind));
    out.push_str(&format!("cornerRadius={}\n", hud.corner_radius));
    module(&mut out, "fps", &hud.fps);
    module(&mut out, "cps", &hud.cps);
    module(&mut out, "keystrokes", &hud.keystrokes);
    module(&mut out, "coords", &hud.coords);
    module(&mut out, "day", &hud.day);
    module(&mut out, "ip", &hud.ip);
    module(&mut out, "armor", &hud.armor);
    module(&mut out, "fullbright", &hud.fullbright);
    module(&mut out, "timeChanger", &hud.time_changer);
    module(&mut out, "ping", &hud.ping);
    module(&mut out, "toggleSneak", &hud.toggle_sneak);
    module(&mut out, "toggleSprint", &hud.toggle_sprint);
    out
}

fn module(out: &mut String, name: &str, module: &HudModule) {
    out.push_str(&format!("{name}.enabled={}\n", module.enabled));
    out.push_str(&format!("{name}.x={:.4}\n", module.x));
    out.push_str(&format!("{name}.y={:.4}\n", module.y));
}

/// Kept next to the jar helpers for callers that only have a game root.
pub fn config_path(root: &Path) -> PathBuf {
    root.join(HUD_CONFIG_NAME)
}

/// Imports HUD changes made in-game into `settings`.
///
/// The mod writes the properties file with a distinct marker when the player edits
/// something in the client. If that marker is present, the file is newer than
/// `settings.json`, so the launcher adopts it before overwriting the file on the
/// next launch. Returns `true` when `settings.hud` changed.
pub fn import_ingame(settings: &mut Settings) -> bool {
    let file = config_path(&settings.game_paths().root);
    let Ok(text) = std::fs::read_to_string(&file) else {
        return false;
    };
    if !text.contains(INGAME_MARKER) {
        return false;
    }
    let Some(parsed) = parse_ingame(&text) else {
        return false;
    };
    let parsed = parsed.into_normalized();
    if settings.hud == parsed {
        return false;
    }
    settings.hud = parsed;
    true
}

fn parse_ingame(text: &str) -> Option<HudSettings> {
    let mut map = std::collections::HashMap::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') || line.starts_with('!') {
            continue;
        }
        if let Some((key, value)) = line.split_once('=') {
            map.insert(key.trim().to_string(), value.trim().to_string());
        }
    }
    if map.is_empty() {
        return None;
    }

    let default = HudSettings::default();
    let boolean = |key: &str, fallback: bool| {
        map.get(key)
            .map(|v| v.eq_ignore_ascii_case("true") || v == "1")
            .unwrap_or(fallback)
    };
    let float = |key: &str, fallback: f32| {
        map.get(key).and_then(|v| v.parse::<f32>().ok()).unwrap_or(fallback)
    };
    let integer = |key: &str, fallback: i32| {
        map.get(key).and_then(|v| v.parse::<i32>().ok()).unwrap_or(fallback)
    };
    let string = |key: &str, fallback: &str| {
        map.get(key).cloned().unwrap_or_else(|| fallback.to_string())
    };
    let module = |name: &str, fallback: HudModule| HudModule {
        enabled: boolean(&format!("{name}.enabled"), fallback.enabled),
        x: float(&format!("{name}.x"), fallback.x),
        y: float(&format!("{name}.y"), fallback.y),
    };

    Some(HudSettings {
        enabled: boolean("enabled", default.enabled),
        scale: float("scale", default.scale),
        background_opacity: float("background", default.background_opacity),
        accent: string("accent", &default.accent),
        text_color: string("text", &default.text_color),
        keybind: integer("keybind", default.keybind),
        corner_radius: integer("cornerRadius", default.corner_radius),
        fps: module("fps", default.fps.clone()),
        cps: module("cps", default.cps.clone()),
        keystrokes: module("keystrokes", default.keystrokes.clone()),
        coords: module("coords", default.coords.clone()),
        day: module("day", default.day.clone()),
        ip: module("ip", default.ip.clone()),
        armor: module("armor", default.armor.clone()),
        fullbright: module("fullbright", default.fullbright.clone()),
        time_changer: module("timeChanger", default.time_changer.clone()),
        ping: module("ping", default.ping.clone()),
        toggle_sneak: module("toggleSneak", default.toggle_sneak.clone()),
        toggle_sprint: module("toggleSprint", default.toggle_sprint.clone()),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::paths;

    #[test]
    fn properties_round_trip_the_important_values() {
        let hud = HudSettings {
            scale: 1.25,
            background_opacity: 0.4,
            accent: "#12ab34".into(),
            text_color: "#fedcba".into(),
            keybind: 345,
            corner_radius: 8,
            keystrokes: HudModule { enabled: false, x: 0.5, y: 0.75 },
            ..HudSettings::default()
        };
        let text = properties(&hud);
        assert!(text.contains("enabled=true"));
        assert!(text.contains("scale=1.250"));
        assert!(text.contains("background=0.400"));
        assert!(text.contains("accent=#12ab34"));
        assert!(text.contains("text=#fedcba"));
        assert!(text.contains("keybind=345"));
        assert!(text.contains("cornerRadius=8"));
        assert!(text.contains("keystrokes.enabled=false"));
        assert!(text.contains("keystrokes.x=0.5000"));
        assert!(text.contains("keystrokes.y=0.7500"));
        assert!(text.contains("fps.enabled=true"));
    }

    #[test]
    fn config_path_matches_the_mod() {
        assert!(paths::GamePaths::new("/g").root.join(HUD_CONFIG_NAME).ends_with("diamond-hud.properties"));
        assert_eq!(config_path(Path::new("/g")), Path::new("/g").join("diamond-hud.properties"));
    }

    #[test]
    fn only_official_26_2_and_newer_are_supported() {
        assert!(!supports("1.21.4"));
        assert!(!supports("1.8.9"));
        assert!(!supports("26.1"));
        assert!(!supports("26w45a"));
        assert!(!supports("26.1"));
        assert!(supports("26.2"));
        assert!(supports("26.3"));
        assert!(supports("27.0"));
    }

    #[test]
    fn in_game_edits_are_imported_and_launcher_files_are_ignored() {
        let mut settings = Settings::default();
        let dir = std::env::temp_dir().join(format!("diamond-hud-import-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        settings.game_dir = Some(dir.to_string_lossy().to_string());
        let file = config_path(&dir);

        let text = format!(
            "#{INGAME_MARKER}\nkeybind=75\nscale=1.500\ncornerRadius=2\nfps.x=0.4000\nfps.y=0.5000\n"
        );
        std::fs::write(&file, text).unwrap();

        assert!(import_ingame(&mut settings));
        assert_eq!(settings.hud.keybind, 75);
        assert_eq!(settings.hud.scale, 1.5);
        assert_eq!(settings.hud.corner_radius, 2);
        assert!((settings.hud.fps.x - 0.4).abs() < 1e-6);

        // A file written by the launcher must not override the saved settings.
        std::fs::write(&file, format!("{LAUNCHER_MARKER}\nkeybind=80\n")).unwrap();
        settings.hud.keybind = 344;
        assert!(!import_ingame(&mut settings));
        assert_eq!(settings.hud.keybind, 344);

        let _ = std::fs::remove_dir_all(&dir);
    }
}